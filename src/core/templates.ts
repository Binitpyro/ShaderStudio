import type { Node, Edge } from "@xyflow/react"
import { useProjectStore, compileQueue, type BackendType, type UniformValue } from "@/stores/projectStore"
import { compileGraph, type GraphNodeData } from "./graphCompiler"
import { STARTER_NODES, STARTER_EDGES, STARTER_VERT_GLSL } from "./defaultStarterScene"
import { SDF_VERT_GLSL } from "./sdf/sdfCompiler"
import templatesJson from "./templatesData.json"

export const TEMPLATE_CATEGORY_NAMES = ["Sci-Fi & VFX", "Atmospheric", "Surfaces & PBR", "Retro & Stylized", "Raymarching & SDF"] as const
export type TemplateCategory = (typeof TEMPLATE_CATEGORY_NAMES)[number]
export type TemplateGeometry = "sphere" | "torus_knot" | "plane" | "cube"

export interface TemplateGraph {
  nodes: Node<GraphNodeData>[]
  edges: Edge[]
}

export interface ShaderTemplate {
  id: string
  name: string
  category: TemplateCategory
  description: string
  /** Informational only: every template runs on all three backends and applying one never switches backend. */
  backend: BackendType
  geometry: TemplateGeometry
  /** WGSL (WebGPU). Hand-ported, never cross-compiled at runtime. Uniform names match the GLSL one 1:1 (plus `mvp`). */
  wgsl: string
  /** GLSL ES 3.00 fragment (WebGL2 and Three.js). */
  glsl: string
  /** Legacy alias of `glsl` (old single-source schema). */
  shaderSource: string
  /** Default values, keyed by uniform name. */
  uniforms: Record<string, UniformValue>
  /** [min, max] for scalar uniforms. */
  ranges: Record<string, [number, number]>
  /** SDF templates: the node graph the sources are generated from (wgsl/glsl above are its compile output). */
  graph?: TemplateGraph
  /** SDF templates: parameter uniforms generated by the graph compile (name -> value). */
  sdfUniforms?: Record<string, number>
}

/** On-disk shape: sources may be a line array (readable diffs) and the pre-W6 single `shaderSource` field is still accepted. */
export interface RawShaderTemplate {
  id: string
  name: string
  category: TemplateCategory
  description: string
  backend?: BackendType
  geometry: TemplateGeometry
  wgsl?: string | string[]
  glsl?: string | string[]
  shaderSource?: string | string[]
  uniforms?: Record<string, UniformValue>
  ranges?: Record<string, [number, number]>
  graph?: TemplateGraph
}

const join = (s: string | string[] | undefined): string => (Array.isArray(s) ? s.join("\n") : (s ?? ""))

/** Raw -> runtime template. Old `shaderSource`-only entries become `glsl` (no wgsl); graph entries get their sources compiled. */
export function normalizeTemplate(raw: RawShaderTemplate): ShaderTemplate {
  let glsl = join(raw.glsl) || join(raw.shaderSource)
  let wgsl = join(raw.wgsl)
  let sdfUniforms: Record<string, number> | undefined
  if (raw.graph) {
    const { queue, error } = compileGraph(raw.graph.nodes, raw.graph.edges)
    if (error) console.warn(`[templates] "${raw.id}": graph failed to compile, sources left empty: ${error}`)
    const step = error ? undefined : queue.find((s) => s.type === "raymarch")
    if (step && step.type === "raymarch") {
      glsl = step.glslSource
      wgsl = step.wgslSource
      sdfUniforms = step.sdfUniforms
    }
  }
  return {
    id: raw.id,
    name: raw.name,
    category: raw.category,
    description: raw.description,
    backend: raw.backend ?? "threejs",
    geometry: raw.geometry,
    wgsl,
    glsl,
    shaderSource: glsl,
    uniforms: raw.uniforms ?? {},
    ranges: raw.ranges ?? {},
    ...(raw.graph ? { graph: raw.graph, sdfUniforms } : {}),
  }
}

export const SHADER_TEMPLATES: ShaderTemplate[] = (templatesJson as unknown as RawShaderTemplate[]).map(normalizeTemplate)

const clone = <T,>(v: T): T => JSON.parse(JSON.stringify(v)) as T

/** The graph a template leaves in the project: its own SDF graph, or the current/starter mesh graph with the template's geometry. */
export function resolveTemplateGraph(template: ShaderTemplate, nodes: Node<GraphNodeData>[], edges: Edge[]): TemplateGraph {
  if (template.graph) return clone(template.graph)
  // A leftover raymarch graph would keep overriding the sources: go back to the plain mesh -> material -> output graph.
  const plain = nodes.length === 0 || nodes.some((n) => n.data.type === "raymarch")
  const base: TemplateGraph = plain ? { nodes: clone(STARTER_NODES), edges: clone(STARTER_EDGES) } : { nodes, edges }
  return {
    nodes: base.nodes.map((n) => (n.type === "mesh" ? { ...n, data: { ...n.data, geometry: template.geometry } } : n)),
    edges: base.edges,
  }
}

/** Writes a template into the open project. Both sources, uniforms and (for SDF) the graph; the active backend is left alone. */
export function applyTemplate(template: ShaderTemplate): void {
  const s = useProjectStore.getState()
  if (template.wgsl) s.setShaderSource(template.wgsl, "wgsl")
  if (template.glsl) s.setShaderSource(template.glsl, "glsl")
  // SDF templates are fullscreen passes: their vertex stage ignores the MVP. Every other template reads the starter
  // stage's `v_world_pos`, which also puts normal MVP rendering back after an SDF one.
  if (template.graph) s.setVertexShaderSource(SDF_VERT_GLSL)
  else if (!s.vertexShaderSource.includes("v_world_pos")) s.setVertexShaderSource(STARTER_VERT_GLSL)

  for (const [key, val] of Object.entries(template.uniforms)) s.setUniformValue(key, val)
  // The starter vertex stage breathes the mesh by u_pulseSpeed: only the hero template wants that.
  if (!("u_pulseSpeed" in template.uniforms)) s.setUniformValue("u_pulseSpeed", { type: "float", value: 0 })
  if (template.sdfUniforms) {
    const values: Record<string, UniformValue> = {}
    for (const [name, value] of Object.entries(template.sdfUniforms)) values[name] = { type: "float", value }
    s.mergeUniformValues(values)
  }

  const graph = resolveTemplateGraph(template, s._graphNodes, s._graphEdges)
  s.setGraphNodes(graph.nodes)
  s.setGraphEdges(graph.edges)
  // Publish the render queue (mesh step: SDF graphs -> "plane") here too, so it never depends on the graph editor being mounted.
  const queue = compileQueue(graph.nodes, graph.edges)
  if (queue) s.setRenderQueue(queue)
  s.triggerRecompile()
}
