use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn get_mime_type(ext: &str) -> &'static str {
    match ext.to_ascii_lowercase().as_str() {
        "html" | "htm" => "text/html; charset=utf-8",
        "js" | "mjs" => "application/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "wasm" => "application/wasm",
        "json" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "ico" => "image/x-icon",
        "webp" => "image/webp",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "ttf" => "font/ttf",
        "otf" => "font/otf",
        "mp3" => "audio/mpeg",
        "wav" => "audio/wav",
        "ogg" => "audio/ogg",
        "glb" => "model/gltf-binary",
        "gltf" => "model/gltf+json",
        "obj" => "text/plain",
        _ => "application/octet-stream",
    }
}

fn collect_files(dir: &Path, base: &Path, list: &mut Vec<(String, PathBuf, &'static str)>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                collect_files(&path, base, list);
            } else if path.is_file() && path.extension().and_then(|e| e.to_str()) != Some("exe") {
                if let Ok(rel) = path.strip_prefix(base) {
                    let rel_str = rel.to_string_lossy().replace('\\', "/");
                    let ext = path
                        .extension()
                        .and_then(|e| e.to_str())
                        .unwrap_or("");
                    let mime = get_mime_type(ext);
                    list.push((rel_str, path.clone(), mime));
                }
            }
        }
    }
}

fn main() {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR not set");
    let dest_path = Path::new(&out_dir).join("assets.rs");

    // Look for dist folder in project root (two levels up from crates/shaderstudio_desktop)
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    let project_root = Path::new(&manifest_dir).join("..").join("..");
    let dist_dir = project_root.join("dist");

    println!("cargo:rerun-if-changed={}", dist_dir.display());

    let mut files = Vec::new();
    if dist_dir.exists() && dist_dir.is_dir() {
        collect_files(&dist_dir, &dist_dir, &mut files);
    }

    let mut code = String::new();
    code.push_str("// Generated by build.rs — Embeds all dist/ assets directly into the binary\n\n");
    code.push_str("#[derive(Clone, Copy)]\n");
    code.push_str("pub struct EmbeddedAsset {\n");
    code.push_str("    pub path: &'static str,\n");
    code.push_str("    pub bytes: &'static [u8],\n");
    code.push_str("    pub mime: &'static str,\n");
    code.push_str("}\n\n");

    code.push_str("pub static EMBEDDED_ASSETS: &[EmbeddedAsset] = &[\n");
    for (rel_path, abs_path, mime) in &files {
        let abs_str = abs_path.to_string_lossy().replace('\\', "\\\\");
        code.push_str(&format!(
            "    EmbeddedAsset {{\n        path: \"{}\",\n        bytes: include_bytes!(\"{}\"),\n        mime: \"{}\",\n    }},\n",
            rel_path, abs_str, mime
        ));
    }
    code.push_str("];\n");

    fs::write(&dest_path, code).expect("Failed to write assets.rs");
}
