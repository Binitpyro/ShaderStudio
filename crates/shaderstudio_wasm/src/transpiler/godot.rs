use super::reflection::ReflectedUniform;

pub fn transpile_to_godot(shader_source: &str, uniforms: &[ReflectedUniform]) -> String {
    let mut godot_uniforms = Vec::new();

    for u in uniforms {
        if u.name == "u_time" || u.name == "time" || u.name == "u_resolution" || u.name == "resolution" {
            continue;
        }

        if u.kind == "color" || u.type_name == "vec4f" {
            godot_uniforms.push(format!("uniform vec4 {} : source_color = vec4(0.8, 0.4, 0.2, 1);", u.name));
        } else if u.type_name == "vec3f" {
            godot_uniforms.push(format!("uniform vec3 {} = vec3(0.4, 0.6, 0.9);", u.name));
        } else if u.type_name == "vec2f" {
            godot_uniforms.push(format!("uniform vec2 {} = vec2(0.5, 0.5);", u.name));
        } else if u.kind == "texture" {
            godot_uniforms.push(format!("uniform sampler2D {} : source_color;", u.name));
        } else {
            godot_uniforms.push(format!("uniform float {} = 1.0;", u.name));
        }
    }

    let uniforms_block = if godot_uniforms.is_empty() {
        "// No custom uniforms".to_string()
    } else {
        godot_uniforms.join("\n")
    };

    let godot_body = shader_source
        .replace("gl_FragCoord.xy", "FRAGCOORD.xy")
        .replace("gl_FragCoord", "FRAGCOORD")
        .replace("u_resolution.xy", "VIEWPORT_SIZE")
        .replace("u_resolution", "VIEWPORT_SIZE")
        .replace("resolution.xy", "VIEWPORT_SIZE")
        .replace("resolution", "VIEWPORT_SIZE")
        .replace("u_time", "TIME")
        .replace("texture2D(", "texture(");

    let indented_body = godot_body
        .lines()
        .map(|l| format!("    {}", l))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
r#"// =====================================================================
// Generated by Shader Studio (Rust Naga Wasm Transpiler)
// Target: Godot 4 Spatial Shader (.gdshader)
// =====================================================================
shader_type spatial;
render_mode cull_back, diffuse_burley, specular_schlick_ggx;

{uniforms_block}

void fragment() {{
    vec2 uv = UV;
    vec4 fragColor = vec4(1.0);

    // --- Shader Studio Shader Logic ---
{indented_body}

    ALBEDO = fragColor.rgb;
    ALPHA = fragColor.a;
    ROUGHNESS = 0.4;
    METALLIC = 0.1;
}}
"#)
}
