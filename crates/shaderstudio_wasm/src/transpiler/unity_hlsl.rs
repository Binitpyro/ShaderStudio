use super::reflection::ReflectedUniform;

pub fn transpile_to_unity_hlsl(
    shader_name: &str,
    shader_source: &str,
    uniforms: &[ReflectedUniform],
) -> String {
    let mut property_lines = Vec::new();
    let mut cbuffer_lines = Vec::new();

    for u in uniforms {
        if u.name == "u_time" || u.name == "time" || u.name == "u_resolution" || u.name == "resolution" {
            continue;
        }

        if u.kind == "color" || u.type_name == "vec4f" {
            property_lines.push(format!("        _{} (\"{}\", Color) = (0.8, 0.4, 0.2, 1)", u.name, u.name));
            cbuffer_lines.push(format!("            float4 _{};", u.name));
        } else if u.type_name == "vec3f" {
            property_lines.push(format!("        _{} (\"{}\", Vector) = (0.4, 0.6, 0.9, 1.0)", u.name, u.name));
            cbuffer_lines.push(format!("            float3 _{};", u.name));
        } else if u.type_name == "vec2f" {
            property_lines.push(format!("        _{} (\"{}\", Vector) = (0.5, 0.5, 0.0, 0.0)", u.name, u.name));
            cbuffer_lines.push(format!("            float2 _{};", u.name));
        } else if u.kind == "texture" {
            property_lines.push(format!("        _{} (\"{}\", 2D) = \"white\" {{}}", u.name, u.name));
        } else {
            property_lines.push(format!("        _{} (\"{}\", Float) = 1.0", u.name, u.name));
            cbuffer_lines.push(format!("            float _{};", u.name));
        }
    }

    let properties_block = if property_lines.is_empty() {
        "        // No exposed properties".to_string()
    } else {
        property_lines.join("\n")
    };

    let cbuffer_block = if cbuffer_lines.is_empty() {
        "            // Per-material constants".to_string()
    } else {
        cbuffer_lines.join("\n")
    };

    // Body replacements using whole token / word boundaries (\b)
    let replacements: [(&str, &str); 26] = [
        ("gl_FragCoord.xy", "i.positionCS.xy"),
        ("gl_FragCoord", "i.positionCS"),
        ("u_resolution.xy", "_ScreenParams.xy"),
        ("u_resolution.x", "_ScreenParams.x"),
        ("u_resolution.y", "_ScreenParams.y"),
        ("u_resolution", "_ScreenParams.xy"),
        ("resolution.xy", "_ScreenParams.xy"),
        ("resolution.x", "_ScreenParams.x"),
        ("resolution.y", "_ScreenParams.y"),
        ("resolution", "_ScreenParams.xy"),
        ("u_time", "_Time.y"),
        ("vec4f", "float4"),
        ("vec3f", "float3"),
        ("vec2f", "float2"),
        ("vec4", "float4"),
        ("vec3", "float3"),
        ("vec2", "float2"),
        ("mat4x4f", "float4x4"),
        ("mat3x3f", "float3x3"),
        ("mat2x2f", "float2x2"),
        ("mat4", "float4x4"),
        ("mat3", "float3x3"),
        ("mat2", "float2x2"),
        ("fract", "frac"),
        ("mix", "lerp"),
        ("texture2D", "tex2D"),
    ];

    let mut hlsl_body = shader_source.to_string();
    for (target, replacement) in replacements {
        hlsl_body = replace_token_boundary(&hlsl_body, target, replacement);
    }

    for u in uniforms {
        if u.name != "u_time" && u.name != "time" && u.name != "u_resolution" && u.name != "resolution" {
            hlsl_body = replace_token_boundary(&hlsl_body, &u.name, &format!("_{}", u.name));
        }
    }

    let indented_body = hlsl_body
        .lines()
        .map(|l| format!("                {}", l))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
r#"// =====================================================================
// Generated by Shader Studio (Rust Naga Wasm Transpiler)
// Target: Unity Universal Render Pipeline (URP) ShaderLab / HLSL
// =====================================================================
Shader "{shader_name}"
{{
    Properties
    {{
{properties_block}
    }}
    SubShader
    {{
        Tags 
        {{ 
            "RenderType" = "Opaque" 
            "RenderPipeline" = "UniversalPipeline"
            "Queue" = "Geometry"
        }}
        LOD 100

        Pass
        {{
            Name "ForwardLit"
            Tags {{ "LightMode" = "UniversalForward" }}

            HLSLPROGRAM
            #pragma vertex vert
            #pragma fragment frag

            #include "Packages/com.unity.render-pipelines.universal/ShaderLibrary/Core.hlsl"

            struct Attributes
            {{
                float4 positionOS : POSITION;
                float2 uv : TEXCOORD0;
                float3 normalOS : NORMAL;
            }};

            struct Varyings
            {{
                float4 positionCS : SV_POSITION;
                float2 uv : TEXCOORD0;
                float3 normalWS : TEXCOORD1;
            }};

            CBUFFER_START(UnityPerMaterial)
{cbuffer_block}
            CBUFFER_END

            Varyings vert(Attributes input)
            {{
                Varyings output;
                output.positionCS = TransformObjectToHClip(input.positionOS.xyz);
                output.uv = input.uv;
                output.normalWS = TransformObjectToWorldNormal(input.normalOS);
                return output;
            }}

            float4 frag(Varyings i) : SV_Target
            {{
                float2 uv = i.uv;
                float4 fragColor = float4(1.0, 1.0, 1.0, 1.0);

                // --- Shader Studio Translated Body ---
{indented_body}

                return fragColor;
            }}
            ENDHLSL
        }}
    }}
    FallBack "Hidden/Universal Render Pipeline/FallbackError"
}}
"#)
}

#[inline]
fn is_ident_char(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// Replaces whole-token / word-bounded occurrences (`\b`) of `target` in `source` with `replacement`.
/// Ensures that identifiers containing `target` as a substring (e.g. `custom_u_resolution`) are not corrupted.
pub fn replace_token_boundary(source: &str, target: &str, replacement: &str) -> String {
    if target.is_empty() {
        return source.to_string();
    }

    let mut result = String::with_capacity(source.len() + 32);
    let bytes = source.as_bytes();
    let target_len = target.len();
    let mut i = 0;

    while i < source.len() {
        if let Some(pos) = source[i..].find(target) {
            let start = i + pos;
            let end = start + target_len;

            let before_ok = start == 0 || !is_ident_char(bytes[start - 1]);
            let after_ok = end >= source.len() || !is_ident_char(bytes[end]);

            if before_ok && after_ok {
                result.push_str(&source[i..start]);
                result.push_str(replacement);
                i = end;
            } else {
                result.push_str(&source[i..start + 1]);
                i = start + 1;
            }
        } else {
            result.push_str(&source[i..]);
            break;
        }
    }

    result
}

#[allow(dead_code)]
fn regex_lite_replace(name: &str, body: &str) -> Result<String, ()> {
    Ok(replace_token_boundary(body, name, &format!("_{}", name)))
}
