pub fn transpile_to_shadertoy(shader_source: &str) -> String {
    let body = shader_source
        .replace("gl_FragCoord.xy", "fragCoord.xy")
        .replace("gl_FragCoord", "fragCoord")
        .replace("u_time", "iTime")
        .replace("u_resolution.xy", "iResolution.xy")
        .replace("u_resolution", "iResolution.xy")
        .replace("resolution.xy", "iResolution.xy")
        .replace("resolution", "iResolution.xy")
        .replace("u_mouse", "iMouse.xy");

    if body.contains("void mainImage(") {
        return format!(
r#"// =====================================================================
// Generated by Shader Studio (Rust Naga Wasm Transpiler)
// Target: Shadertoy GLSL ES 3.0
// =====================================================================
{}
"#, body);
    }

    let indented_body = body
        .lines()
        .map(|l| format!("    {}", l))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
r#"// =====================================================================
// Generated by Shader Studio (Rust Naga Wasm Transpiler)
// Target: Shadertoy GLSL ES 3.0
// =====================================================================

void mainImage( out vec4 fragColor, in vec2 fragCoord )
{{
    vec2 uv = fragCoord.xy / iResolution.xy;
    fragColor = vec4(1.0);

    // --- Shader Studio Converted Logic ---
{}
}}
"#, indented_body)
}
